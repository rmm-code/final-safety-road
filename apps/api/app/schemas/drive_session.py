from __future__ import annotations

import uuid
from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field


class DriveSessionCreate(BaseModel):
    """Start of a drive.

    `id` is generated by the phone, so a drive started without signal is still one drive:
    its sightings carry this id from the first frame, and the session is created whenever
    the phone next reaches the server. Creating the same id again returns the session
    rather than failing, which is what makes that retry safe.
    """

    id: uuid.UUID | None = None
    started_at: datetime | None = None
    device_name: str | None = Field(default=None, max_length=200)
    platform: str | None = Field(default=None, max_length=100)
    browser: str | None = Field(default=None, max_length=200)


class DriveSessionEnd(BaseModel):
    """When the drive actually ended, which a phone out of signal reports late."""

    ended_at: datetime | None = None


class DriveSessionOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    user_id: uuid.UUID
    device_id: uuid.UUID | None
    started_at: datetime
    ended_at: datetime | None
    status: str
    event_count: int = 0
